import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { configuredLocales, localeConfig } from '../localization/config.mjs';
import { fingerprint, placeholders, sourceHash } from '../localization/checksums.mjs';
import { isServerOnlyPricingSource } from '../localization/server-only-pricing.mjs';

const root = resolve(import.meta.dirname, '..');
const catalog = JSON.parse(await readFile(resolve(root, 'localization/catalog.json'), 'utf8'));
const translations = {};
for (const locale of configuredLocales) {
  if (locale === localeConfig.defaultLocale) continue;
  translations[locale] = JSON.parse(await readFile(resolve(root, `localization/translations/${locale}.json`), 'utf8'));
}

const allResources = {};
const resources = {};
for (const locale of configuredLocales) {
  const messages = {};
  for (const entry of catalog.strings) {
    if (locale === localeConfig.defaultLocale) {
      messages[entry.key] = entry.source;
      continue;
    }
    const translated = translations[locale].entries[entry.key];
    if (!translated || translated.status !== 'approved' || translated.sourceHash !== sourceHash(entry)
      || translated.fingerprint !== fingerprint(entry, locale, catalog)
      || JSON.stringify(placeholders(translated.text)) !== JSON.stringify(placeholders(entry.source))) {
      throw new Error(`${locale}: translation is missing or not approved for ${entry.key}`);
    }
    messages[entry.key] = translated.text;
  }
  allResources[locale] = messages;
  resources[locale] = Object.fromEntries(Object.entries(messages).filter(([source]) => !isServerOnlyPricingSource(source)));
}
const output = `// Generated by web/scripts/build-localization.mjs. Do not edit directly.\n`
  + `export const en = Object.freeze({ translation: Object.freeze(${JSON.stringify(resources.en, null, 2)}) });\n\n`
  + `export const zhTW = Object.freeze({ translation: Object.freeze(${JSON.stringify(resources['zh-TW'], null, 2)}) });\n\n`
  + `export const zhCN = Object.freeze({ translation: Object.freeze(${JSON.stringify(resources['zh-CN'], null, 2)}) });\n\n`
  + `export const resources = Object.freeze({ en, 'zh-TW': zhTW, 'zh-CN': zhCN });\n`;
await writeFile(resolve(root, 'src/i18n/resources.generated.mjs'), output);
const serviceDescriptionSources = new Set([
  'Account and tenant APIs',
  'Platform admin console',
  'Central log backend',
  'TURN relay host exporter',
  'Cloud-to-device or cloud-to-app file delivery.',
  'Deliver an update task to a target device.',
  'Ingest runtime logs for diagnosis.',
  'Keep runtime logs available for review.',
  'Live media sent through the cloud relay.',
  'Messages accepted from devices or applications.',
  'Messages delivered to subscribers.',
  'Other device and application data API calls.',
  'Read media or firmware from storage.',
  'Read, update, delete and list device state.',
  'Stored clips, snapshots and firmware artifacts.',
  'Upload clips, snapshots and firmware objects.',
]);
const apiResources = {};
for (const locale of configuredLocales.filter(value => value !== localeConfig.defaultLocale)) {
  apiResources[locale] = { system: {}, service: {} };
  for (const entry of catalog.strings) {
    apiResources[locale].system[entry.source] = allResources[locale][entry.key];
    if (serviceDescriptionSources.has(entry.source)) apiResources[locale].service[entry.source] = allResources[locale][entry.key];
  }
}
await writeFile(resolve(root, '../internal/app/localization.generated.json'), `${JSON.stringify(apiResources, null, 2)}\n`);
console.log(`Compiled ${catalog.strings.length} messages for ${configuredLocales.join(', ')}.`);
